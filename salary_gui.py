import ipywidgets as widgets
from IPython.display import display
import pandas as pd
import joblib

model = joblib.load("salary_prediction_model.pkl")

age = widgets.IntText(value=30,description="Age:")
experience = widgets.IntText(value=5,description="Experience:")
education = widgets.Dropdown(
    options=["Bachelor", "Master", "PhD"],
    description="Education:"
)

button = widgets.Button(
    description="Predict Salary",
    button_style="primary"
)

result = widgets.Output()


def get_experience_group(x):
    if x <= 2:
        return "Beginner"
    elif x <= 5:
        return "Junior"
    elif x <= 10:
        return "Mid-Level"
    else:
        return "Senior"


def predict_salary(b):
    with result:
        result.clear_output()

        exp_group = get_experience_group(experience.value)

        data = pd.DataFrame({
            "Age": [age.value],
            "Experience": [experience.value],
            "Education": [education.value],
            "Experience_Group": [exp_group]
        })

        prediction = model.predict(data)[0]


        print(f"Age: {age.value}")
        print(f"Experience: {experience.value} years")
        print(f"Education: {education.value}")
        print(f"Experience Group: {exp_group}")
        print(f"Predicted Salary: Rs. {prediction:,.0f}")


button.on_click(predict_salary)


display(
    widgets.VBox([
        widgets.HTML("<h2>Salary Prediction</h2>"),
        age,
        experience,
        education,
        button,
        result
    ])
)